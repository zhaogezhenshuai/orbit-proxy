import CryptoKit
import Foundation

public enum CoreError: Error, CustomStringConvertible {
    case binaryNotFound
    case notReady(String)
    case authorizationFailed(String)
    case portInUse(Int)

    public var description: String {
        switch self {
        case .binaryNotFound: return "找不到 mihomo 内核"
        case .notReady(let log): return "内核启动失败：\(log)"
        case .authorizationFailed(let m): return "管理员授权失败：\(m)"
        case .portInUse(let p): return "端口 \(p) 已被其他程序占用，请在设置里换一个端口，或先退出占用它的程序"
        }
    }
}

/// Runs the mihomo core either as the current user (system-proxy mode) or as root through an
/// administrator prompt (TUN mode). The root core is supervised by a small watcher that kills it
/// when the app exits or a stop-file appears, so stopping it never needs a second password prompt.
///
/// The root core never runs from, reads through or writes to user-writable paths once started:
/// the launcher copies the binary, config and rule-sets into a root-owned directory and runs
/// everything there. Otherwise any process running as the user could plant a symlink or hard link
/// (e.g. to /etc/sudoers) where the root core writes, and get root without the password.
/// The launcher also checks the copied binary and config against hashes the app computed, and
/// gives the root core a one-time API secret that only the app learns, so other processes running
/// as the user can neither swap what runs as root nor drive the root core's REST API.
public final class CoreProcess: @unchecked Sendable {
    public let store: Store
    public let binary: URL
    private var process: Process?
    private var rootPID: Int32?
    /// API secret of the running root core, generated by the launcher; never written to the user's files.
    public private(set) var rootSecret: String?

    public private(set) var runningAsRoot = false
    public var isRunning: Bool { process?.isRunning == true || rootPID.map { kill($0, 0) == 0 || errno == EPERM } == true }

    /// "core" is the real proxy; "probe" is a listener-less core used only for latency tests while disconnected.
    public let profile: String

    public init(store: Store, binary: URL, profile: String = "core") {
        self.store = store
        self.binary = binary
        self.profile = profile
    }

    var isMain: Bool { profile == "core" }
    public var configFile: URL { isMain ? store.configFile : store.root.appendingPathComponent("\(profile).yaml") }
    var userLogFile: URL { isMain ? store.logFile : store.root.appendingPathComponent("\(profile).log") }
    /// The current core's log: in the root-owned directory while the TUN core runs.
    public var logFile: URL { runningAsRoot ? Self.rootDir.appendingPathComponent("core.log") : userLogFile }
    var userHome: URL {
        let dir = isMain ? store.homeDir : store.root.appendingPathComponent(profile, isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    /// Root-owned working directory of the TUN core. Only root can create entries in
    /// /Library/Application Support, so the user can't pre-plant anything here.
    public static let rootDir = URL(fileURLWithPath: "/Library/Application Support/Orbit", isDirectory: true)
    /// Rule-set path in the TUN core's config, relative to its working directory.
    public static let rootRulesetDir = "ruleset"

    /// Finds the core: the app bundle's own copy, or for command-line and development builds
    /// `ORBIT_CORE`, the executable's directory or the repo's build output. Inside Orbit.app only
    /// the bundled core counts, so an environment variable can't point the root launcher elsewhere.
    public static func locateBinary() -> URL? {
        if Bundle.main.bundleURL.pathExtension == "app", let r = Bundle.main.resourceURL {
            let bundled = r.appendingPathComponent("mihomo")
            return FileManager.default.isExecutableFile(atPath: bundled.path) ? bundled : nil
        }
        var candidates: [URL] = []
        if let env = ProcessInfo.processInfo.environment["ORBIT_CORE"] { candidates.append(URL(fileURLWithPath: env)) }
        let exe = URL(fileURLWithPath: CommandLine.arguments[0]).resolvingSymlinksInPath().deletingLastPathComponent()
        candidates.append(exe.appendingPathComponent("mihomo"))
        var dir = exe
        for _ in 0..<5 {
            candidates.append(dir.appendingPathComponent(".toolchain/mihomo"))
            dir = dir.deletingLastPathComponent()
        }
        return candidates.first { FileManager.default.isExecutableFile(atPath: $0.path) }
    }

    /// Created by the app to stop the root core; the watcher only checks that it exists.
    var stopFile: URL { store.root.appendingPathComponent("core-root.stop") }
    var pidFile: URL { store.root.appendingPathComponent("\(profile).pid") }
    /// Config handed to the TUN core: rule-set paths relative to its own directory.
    var rootConfigFile: URL { store.root.appendingPathComponent("config-root.yaml") }

    /// `rootConfig` is required when `asRoot` is true.
    /// `ports` are checked first: a port held by another program would leave the core half started.
    public func start(asRoot: Bool, rootConfig: Data? = nil, ports: [Int] = []) throws {
        stop()
        killStale()
        if let busy = ports.first(where: Self.portInUse) { throw CoreError.portInUse(busy) }
        if asRoot {
            guard let rootConfig else { throw CoreError.notReady("missing TUN config") }
            try startRoot(config: rootConfig)
        } else {
            try startUser()
        }
        runningAsRoot = asRoot
    }

    private func startUser() throws {
        FileManager.default.createFile(atPath: userLogFile.path, contents: nil)
        let p = Process()
        p.executableURL = binary
        p.arguments = ["-d", userHome.path, "-f", configFile.path]
        var env = ProcessInfo.processInfo.environment
        env["SAFE_PATHS"] = store.rulesetDir.path
        p.environment = env
        let log = try FileHandle(forWritingTo: userLogFile)
        p.standardOutput = log
        p.standardError = log
        try p.run()
        process = p
        try? String(p.processIdentifier).write(to: pidFile, atomically: true, encoding: .utf8)
    }

    /// Text of the macOS administrator prompt shown when TUN mode starts (the app localizes it).
    public static var adminPrompt = "Orbit 需要管理员权限以开启增强模式 (TUN)"

    /// SHA-256 the bundled core must have: recorded in Info.plist by scripts/build-app.sh, so a core
    /// swapped inside the bundle is refused. Development builds without that key hash the file.
    static func expectedCoreHash(of binary: URL) throws -> String {
        if let h = Bundle.main.object(forInfoDictionaryKey: "OrbitCoreSHA256") as? String, h.count == 64 { return h.lowercased() }
        return sha256Hex(try Data(contentsOf: binary, options: .mappedIfSafe))
    }

    static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func startRoot(config: Data) throws {
        try config.write(to: rootConfigFile, options: .atomic)
        // The launcher has copied it by the time the prompt returns; it holds no secret, but needn't linger.
        defer { try? FileManager.default.removeItem(at: rootConfigFile) }
        try? FileManager.default.removeItem(at: stopFile)
        // The launcher goes inline to `sh -c`, never through a file the user could swap out.
        let args = [Self.launcherScript, "orbit-tun", binary.path, try Self.expectedCoreHash(of: binary),
                    rootConfigFile.path, Self.sha256Hex(config), store.rulesetDir.path,
                    stopFile.path, String(getpid()), Self.rootDir.path, Self.watcherScript, String(getuid())]
        let shell = "/bin/sh -c " + args.map(Self.shellQuote).joined(separator: " ")
        let apple = "do shell script \"\(Self.appleScriptEscape(shell))\" with prompt \"\(Self.appleScriptEscape(Self.adminPrompt))\" with administrator privileges"
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/osascript")
        p.arguments = ["-e", apple]
        let out = Pipe(), err = Pipe()
        p.standardOutput = out
        p.standardError = err
        try p.run()
        p.waitUntilExit()
        let o = String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        let fields = o.split(whereSeparator: \.isWhitespace)
        guard p.terminationStatus == 0, fields.count == 2, let pid = Int32(fields[0]), fields[1].count >= 32 else {
            throw CoreError.authorizationFailed(String(decoding: err.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self))
        }
        rootPID = pid
        rootSecret = String(fields[1])
    }

    /// Whether another program listens on `port`, on any address or on loopback. Binding with
    /// SO_REUSEADDR ignores leftover TIME_WAIT connections from our own previous core.
    static func portInUse(_ port: Int) -> Bool {
        for host in ["0.0.0.0", "127.0.0.1"] {
            let fd = socket(AF_INET, SOCK_STREAM, 0)
            guard fd >= 0 else { continue }
            defer { close(fd) }
            var on: Int32 = 1
            setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &on, socklen_t(MemoryLayout<Int32>.size))
            var addr = sockaddr_in()
            addr.sin_len = UInt8(MemoryLayout<sockaddr_in>.size)
            addr.sin_family = sa_family_t(AF_INET)
            addr.sin_port = in_port_t(UInt16(truncatingIfNeeded: port)).bigEndian
            inet_pton(AF_INET, host, &addr.sin_addr)
            let r = withUnsafePointer(to: &addr) {
                $0.withMemoryRebound(to: sockaddr.self, capacity: 1) { bind(fd, $0, socklen_t(MemoryLayout<sockaddr_in>.size)) }
            }
            if r != 0 && errno == EADDRINUSE { return true }
        }
        return false
    }

    static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    static func appleScriptEscape(_ s: String) -> String {
        s.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n")
    }

    public func stop() {
        if let p = process, p.isRunning {
            p.terminate()
            let deadline = Date().addingTimeInterval(3)
            while p.isRunning && Date() < deadline { usleep(50_000) }
            if p.isRunning { kill(p.processIdentifier, SIGKILL) }
        }
        // Only our own core's pid file: one left by a crashed run is for killStale() to act on.
        if process != nil { try? FileManager.default.removeItem(at: pidFile) }
        process = nil
        if let pid = rootPID {
            FileManager.default.createFile(atPath: stopFile.path, contents: nil)
            let deadline = Date().addingTimeInterval(4)
            while (kill(pid, 0) == 0 || errno == EPERM) && Date() < deadline { usleep(100_000) }
            try? FileManager.default.removeItem(at: stopFile)
        }
        rootPID = nil
        rootSecret = nil
        runningAsRoot = false
    }

    /// Kills a user-mode core left behind by a crashed previous run: the one in our pid file, and
    /// any process running our core binary on this profile's working directory (older versions
    /// could lose the pid file). Matching both binary and directory never touches other programs.
    private func killStale() {
        var pids: Set<Int32> = []
        if let s = try? String(contentsOf: pidFile, encoding: .utf8), let pid = Int32(s.trimmingCharacters(in: .whitespacesAndNewlines)) {
            var buf = [CChar](repeating: 0, count: 1024)
            if proc_pidpath(pid, &buf, UInt32(buf.count)) > 0, String(cString: buf).hasSuffix("/mihomo") { pids.insert(pid) }
        }
        pids.formUnion(Self.processes(commandPrefix: "\(binary.path) -d \(userHome.path) "))
        pids.remove(getpid())
        if let own = process?.processIdentifier { pids.remove(own) }
        for pid in pids { kill(pid, SIGTERM) }
        // Wait for them to let go of their ports, or the new core can't bind them.
        let deadline = Date().addingTimeInterval(3)
        while pids.contains(where: { kill($0, 0) == 0 }) && Date() < deadline { usleep(50_000) }
        for pid in pids where kill(pid, 0) == 0 { kill(pid, SIGKILL) }
        if !pids.isEmpty { usleep(200_000) }
        try? FileManager.default.removeItem(at: pidFile)
    }

    /// This user's processes whose command line starts with `prefix`.
    static func processes(commandPrefix prefix: String) -> [Int32] {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/bin/ps")
        p.arguments = ["-x", "-U", String(getuid()), "-o", "pid=,command="]
        let out = Pipe()
        p.standardOutput = out
        p.standardError = FileHandle.nullDevice
        guard (try? p.run()) != nil else { return [] }
        let text = String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        p.waitUntilExit()
        return text.split(separator: "\n").compactMap { line in
            let t = line.drop { $0 == " " }
            guard let sp = t.firstIndex(of: " "), let pid = Int32(t[..<sp]) else { return nil }
            return t[t.index(after: sp)...].hasPrefix(prefix) ? pid : nil
        }
    }

    public func waitUntilReady(api: MihomoAPI, timeout: TimeInterval = 15) async throws {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if (try? await api.version()) != nil { return }
            if !isRunning { break }
            try await Task.sleep(nanoseconds: 200_000_000)
        }
        throw CoreError.notReady(tailLog(lines: 8))
    }

    public func tailLog(lines: Int = 50) -> String {
        guard let d = try? Data(contentsOf: logFile) else { return "" }
        return String(decoding: d, as: UTF8.self).split(separator: "\n").suffix(lines).joined(separator: "\n")
    }

    /// Runs as root via `sh -c`. Args: core core_sha256 config config_sha256 rulesets stopfile app_pid dir watcher uid.
    /// Reads the user's files with the user's own rights (`sudo -u`), so a link to a root-only file
    /// can't be read through, then works solely inside the root-owned `dir`. The copied core and
    /// config must match the hashes the app passed, which closes the window between the app
    /// writing them and the administrator prompt returning. Prints "<pid> <api secret>".
    static let launcherScript = #"""
    set -eu
    CORE="$1"; CORE_SHA="$2"; CFG="$3"; CFG_SHA="$4"; RULES="$5"; STOP="$6"; APP_PID="$7"; D="$8"; WATCHER="$9"; OWNER="${10}"
    case "$OWNER" in ''|0|*[!0-9]*) echo "bad user id" >&2; exit 1 ;; esac
    asuser() { /usr/bin/sudo -n -u "#$OWNER" "$@"; }
    sha() { /usr/bin/shasum -a 256 "$1" | cut -d ' ' -f 1; }
    umask 077
    mkdir -p "$D"
    chown root:wheel "$D"
    chmod 755 "$D"
    # Stop a core left over from a crashed run before replacing its files.
    if [ -f "$D/core.pid" ]; then
      OLD=$(cat "$D/core.pid")
      [ "$(ps -p "$OLD" -o comm= 2>/dev/null || true)" = "$D/mihomo" ] && kill "$OLD" 2>/dev/null && sleep 1 || true
    fi
    rm -f "$D/mihomo.new"
    asuser /bin/cat "$CORE" > "$D/mihomo.new"
    [ "$(sha "$D/mihomo.new")" = "$CORE_SHA" ] || { rm -f "$D/mihomo.new"; echo "core checksum mismatch" >&2; exit 1; }
    chmod 755 "$D/mihomo.new"
    mv -f "$D/mihomo.new" "$D/mihomo"
    mkdir -p "$D/home"
    chmod 700 "$D/home"
    rm -rf "$D/home/ruleset"
    mkdir -m 700 "$D/home/ruleset"
    for f in "$RULES"/*.mrs; do
      [ -f "$f" ] && [ ! -L "$f" ] || continue
      asuser /bin/cat "$f" > "$D/home/ruleset/$(basename "$f")" || rm -f "$D/home/ruleset/$(basename "$f")"
    done
    asuser /bin/cat "$CFG" > "$D/home/config.yaml"
    [ "$(sha "$D/home/config.yaml")" = "$CFG_SHA" ] || { rm -f "$D/home/config.yaml"; echo "config checksum mismatch" >&2; exit 1; }
    printf '%s\n' "$WATCHER" > "$D/watch.sh"
    chmod 644 "$D/watch.sh"
    # The log lists every domain visited; only the user may read it.
    : > "$D/core.log"
    chown "$OWNER" "$D/core.log"
    chmod 600 "$D/core.log"
    SECRET=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 40)
    CLASH_OVERRIDE_SECRET="$SECRET" nohup "$D/mihomo" -d "$D/home" -f "$D/home/config.yaml" >>"$D/core.log" 2>&1 </dev/null &
    CORE_PID=$!
    echo "$CORE_PID" > "$D/core.pid"
    chmod 644 "$D/core.pid"
    nohup /bin/sh "$D/watch.sh" "$CORE_PID" "$STOP" "$APP_PID" "$D/mihomo" >/dev/null 2>&1 </dev/null &
    echo "$CORE_PID $SECRET"
    """#

    /// Root watcher: stops the core when the app exits or creates the stop-file. Checks the pid
    /// still belongs to the core before every kill, so a reused pid is never signalled.
    static let watcherScript = #"""
    CORE_PID="$1"; STOP="$2"; APP_PID="$3"; CORE="$4"
    alive() { [ "$(ps -p "$CORE_PID" -o comm= 2>/dev/null)" = "$CORE" ]; }
    while kill -0 "$APP_PID" 2>/dev/null && alive && [ ! -e "$STOP" ]; do sleep 1; done
    if alive; then kill "$CORE_PID"; sleep 1; fi
    if alive; then kill -9 "$CORE_PID"; fi
    exit 0
    """#
}
